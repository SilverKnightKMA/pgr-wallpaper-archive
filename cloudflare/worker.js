/**
 * PGR Wallpaper Archive — random wallpaper endpoint.
 *
 * Serves TRUE binary-capable HTTP responses (302 → raw.githubusercontent.com)
 * on the paths requested by the repo owner:
 *
 *   https://blog.tungvuthanh.com/pgr-wallpaper-archive/wallpapers  → random (all)
 *   https://blog.tungvuthanh.com/pgr-wallpaper-archive/desktop     → random desktop
 *   https://blog.tungvuthanh.com/pgr-wallpaper-archive/mobile      → random mobile
 *
 * Optional query params:
 *   ?server=jp        restrict to one server (cn | jp | global | tw | kr)
 *   ?preview=1        redirect to the lightweight .jpg preview instead of the full image
 *
 * Data source: docs/index-data.json on the GitHub Pages site (regenerated by
 * src/generate_readme.py on every archive batch). Deploy steps: cloudflare/README.md.
 */

const SITE = 'https://blog.tungvuthanh.com/pgr-wallpaper-archive';
const INDEX_URL = `${SITE}/index-data.json`;
// Edge-cache the index for 6h; the random pick itself is per-request.
const INDEX_CACHE_TTL = 21600;

function pickRandom(items, category, server) {
  const pool = items.filter(
    ([, c, s]) => (!category || c === category) && (!server || s === server)
  );
  if (!pool.length) return null;
  return pool[Math.floor(Math.random() * pool.length)];
}

export default {
  async fetch(request) {
    const url = new URL(request.url);
    const segment = url.pathname.replace(/\/+$/, '').split('/').pop();
    const category = segment === 'desktop' || segment === 'mobile' ? segment : null;
    if (segment !== 'wallpapers' && category === null) {
      return new Response('Not found', { status: 404 });
    }
    const server = url.searchParams.get('server');
    const preview = url.searchParams.get('preview') === '1';

    let index;
    try {
      const res = await fetch(INDEX_URL, {
        cf: { cacheTtl: INDEX_CACHE_TTL, cacheEverything: true },
      });
      if (!res.ok) throw new Error(`index fetch ${res.status}`);
      index = await res.json();
    } catch (e) {
      return new Response(`index-data.json unavailable: ${e.message}`, {
        status: 502,
      });
    }

    const entry = pickRandom(index.items, category, server);
    if (!entry) {
      return new Response('No wallpapers match this filter', { status: 404 });
    }
    const [filename, cat] = entry;
    const encoded = encodeURIComponent(filename);

    // Always GitHub-hosted URLs (the archive's own copies), never the Kuro CDN.
    const location = preview
      ? `https://raw.githubusercontent.com/${index.repo}/${index.previewBranch}/previews/${encodeURIComponent(
          filename.replace(/\.[^.]+$/, '') + '.jpg'
        )}`
      : `https://raw.githubusercontent.com/${index.repo}/${index.wallpapersBranch}/${cat}/${encoded}`;

    return new Response(null, {
      status: 302,
      headers: {
        Location: location,
        'Cache-Control': 'no-store',
        'Access-Control-Allow-Origin': '*',
      },
    });
  },
};
