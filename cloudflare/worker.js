/**
 * PGR Wallpaper Archive — random wallpaper endpoint.
 *
 * DEFAULT: proxies the actual image BYTES (first response is the image,
 * content-type image/jpeg|png) — works with every client, including tools
 * that do not follow redirects.
 *
 *   https://pgr-random.tungvt1912.workers.dev/wallpapers   → random (all)
 *   https://pgr-random.tungvt1912.workers.dev/desktop      → random desktop
 *   https://pgr-random.tungvt1912.workers.dev/mobile       → random mobile
 *
 * Query params:
 *   ?server=jp        restrict to one server (cn | jp | global | tw | kr)
 *   ?preview=1        serve the lightweight .jpg preview instead of the full image
 *   ?redirect=1       302 redirect to raw.githubusercontent.com instead of
 *                     proxying bytes (client downloads straight from GitHub CDN)
 *
 * The content-type is derived from the filename extension because the CDN
 * occasionally mislabels images as application/octet-stream (observed on
 * raw.githubusercontent.com), which makes browsers download instead of
 * displaying the image.
 *
 * Data source: docs/index-data.json (regenerated by src/generate_readme.py on
 * every archive batch). Deploy steps: cloudflare/README.md.
 */

// Fetch the index straight from raw.githubusercontent.com (Fastly CDN,
// ~0.2s TTFB) instead of the Pages host — the Pages chain (CF -> GitHub
// Pages origin) occasionally took 5-12s on cache miss.
const INDEX_URL =
  'https://raw.githubusercontent.com/SilverKnightKMA/pgr-wallpaper-archive/main/docs/index-data.json';
// Edge-cache the index for 6h; the random pick itself is per-request.
const INDEX_CACHE_TTL = 21600;
// In-isolate cache: most requests skip the index fetch entirely.
// 6h matches the archive batch cadence (daily) and the edge cache TTL.
const ISOLATE_CACHE_TTL = 6 * 60 * 60 * 1000;
let isolateIndex = null;
let isolateIndexAt = 0;

const UPSTREAM_TIMEOUT_MS = 15000;

const EXT_TYPES = {
  jpg: 'image/jpeg',
  jpeg: 'image/jpeg',
  png: 'image/png',
  webp: 'image/webp',
  gif: 'image/gif',
  bmp: 'image/bmp',
};

function contentTypeFor(name, upstreamType) {
  const m = name.toLowerCase().match(/\.([a-z0-9]+)$/);
  if (m && EXT_TYPES[m[1]]) return EXT_TYPES[m[1]];
  return upstreamType && upstreamType.startsWith('image/') ? upstreamType : 'application/octet-stream';
}

async function loadIndex() {
  const now = Date.now();
  if (isolateIndex && now - isolateIndexAt < ISOLATE_CACHE_TTL) {
    return isolateIndex;
  }
  const res = await fetch(INDEX_URL, {
    cf: { cacheTtl: INDEX_CACHE_TTL, cacheEverything: true },
    signal: AbortSignal.timeout(10000),
  });
  if (!res.ok) {
    // fall back to a stale isolate copy rather than failing outright
    if (isolateIndex) return isolateIndex;
    throw new Error(`index fetch ${res.status}`);
  }
  isolateIndex = await res.json();
  isolateIndexAt = now;
  return isolateIndex;
}

function pickRandom(items, category, server) {
  const pool = items.filter(
    ([, c, s]) => (!category || c === category) && (!server || s === server)
  );
  if (!pool.length) return null;
  return pool[Math.floor(Math.random() * pool.length)];
}

export default {
  async fetch(request) {
    const url = new URL(request.url);
    const segment = url.pathname.replace(/\/+$/, '').split('/').pop();
    const category = segment === 'desktop' || segment === 'mobile' ? segment : null;
    if (segment !== 'wallpapers' && category === null) {
      return new Response('Not found', { status: 404 });
    }
    const server = url.searchParams.get('server');
    const preview = url.searchParams.get('preview') === '1';
    const wantRedirect = url.searchParams.get('redirect') === '1';

    let index;
    try {
      index = await loadIndex();
    } catch (e) {
      return new Response(`index-data.json unavailable: ${e.message}`, {
        status: 502,
      });
    }

    // Upstream fetches can hang (observed rare multi-minute stalls on cold
    // large objects). Timeout + one retry with a fresh random pick.
    let lastErr = null;
    for (let attempt = 0; attempt < 2; attempt++) {
      const entry = pickRandom(index.items, category, server);
      if (!entry) {
        return new Response('No wallpapers match this filter', { status: 404 });
      }
      const [filename, cat] = entry;
      const encoded = encodeURIComponent(filename);

      // Always GitHub-hosted URLs (the archive's own copies), never the Kuro CDN.
      const servedName = preview ? filename.replace(/\.[^.]+$/, '') + '.jpg' : filename;
      const upstream = preview
        ? `https://raw.githubusercontent.com/${index.repo}/${index.previewBranch}/previews/${encodeURIComponent(servedName)}`
        : `https://raw.githubusercontent.com/${index.repo}/${index.wallpapersBranch}/${cat}/${encoded}`;

      if (wantRedirect) {
        return new Response(null, {
          status: 302,
          headers: {
            Location: upstream,
            'Cache-Control': 'no-store',
            'Access-Control-Allow-Origin': '*',
          },
        });
      }

      const fwdHeaders = {};
      const range = request.headers.get('range');
      if (range) fwdHeaders['Range'] = range;

      let upstreamRes;
      try {
        upstreamRes = await fetch(upstream, {
          headers: fwdHeaders,
          signal: AbortSignal.timeout(UPSTREAM_TIMEOUT_MS),
        });
      } catch (e) {
        lastErr = e;
        continue; // retry with a fresh random pick
      }
      if (!upstreamRes.ok && upstreamRes.status !== 206) {
        lastErr = new Error(`upstream ${upstreamRes.status}`);
        continue;
      }

      const headers = {
        'Cache-Control': 'no-store',
        'Access-Control-Allow-Origin': '*',
        'X-Random-Source': upstream,
        // derive from filename: the CDN sometimes mislabels images
        'Content-Type': contentTypeFor(servedName, upstreamRes.headers.get('Content-Type')),
      };
      for (const h of ['Content-Length', 'Content-Range']) {
        const v = upstreamRes.headers.get(h);
        if (v) headers[h] = v;
      }
      return new Response(upstreamRes.body, {
        status: upstreamRes.status,
        headers,
      });
    }
    return new Response(`upstream failed twice: ${lastErr && lastErr.message}`, {
      status: 502,
    });
  },
};
